import { type HomeSection, type SiteInfo } from '@pythagoras/shared';
import type { Metadata } from 'next';
import { headers } from 'next/headers';
import { notFound } from 'next/navigation';
import { type ReactNode } from 'react';
import { lookUpSite, publishedPages } from '../../../lib/cms';
import { runtime } from '../../../lib/server';
import { defaultIntro, menu, pageSlug, SITE_HOST_HEADER, siteUrl } from '../../../lib/sites';
import { Logo } from '../../brand';
import { DevelopmentBanner } from '../../development-banner';
import { Icon } from '../../icons';
import { SiteFooter, SiteHeader } from '../site-frame';

export const dynamic = 'force-dynamic';

type Params = Promise<{ path?: string[] }>;

/** The host the proxy rewrote this request for; absent means someone asked for /sites directly. */
async function siteHost(): Promise<string> {
  const host = (await headers()).get(SITE_HOST_HEADER);
  if (!host) notFound();
  return host;
}

export async function generateMetadata({ params }: { params: Params }): Promise<Metadata> {
  const { config } = runtime();
  const site = await lookUpSite(config.API_INTERNAL_URL, await siteHost());
  if (site.kind !== 'ok') return { title: 'Pythagoras' };
  const { path } = await params;
  const slug = pageSlug(path);
  if (!slug || slug === 'home' || !site.value.cmsKey) return { title: site.value.name };
  const pages = await publishedPages(config.CMS_INTERNAL_URL, site.value.cmsKey);
  const page = pages.kind === 'ok' ? pages.value.find((candidate) => candidate.slug === slug) : undefined;
  return { title: `${page?.title ?? slug.replace(/-/g, ' ')} · ${site.value.name}` };
}

/** A public school or group website (M3.5, ADR 0017): its CMS pages, or a start page from the platform. */
export default async function WebsitePage({ params }: { params: Params }) {
  const { path } = await params;
  const slug = pageSlug(path);
  if (!slug) notFound();
  const { config } = runtime();

  const site = await lookUpSite(config.API_INTERNAL_URL, await siteHost());
  if (site.kind === 'missing') notFound();
  if (site.kind === 'unavailable') return <Unavailable />;

  const pages = site.value.cmsKey ? await publishedPages(config.CMS_INTERNAL_URL, site.value.cmsKey) : null;
  if (pages?.kind === 'unavailable') return <Unavailable name={site.value.name} />;
  const all = pages?.kind === 'ok' ? pages.value : [];
  const page = all.find((candidate) => candidate.slug === slug);
  if (!page && slug !== 'home') notFound();

  const links = menu(all);
  const canAsk = site.value.schools.length > 0;
  const home = slug === 'home';
  const actions =
    home && canAsk ? (
      <p className="site-hero-actions">
        <a href="/inquiry" className="button">
          Ask about a place
        </a>
        <a href={config.APP_URL} className="button secondary">
          Family portal
        </a>
      </p>
    ) : null;
  const blocks: Record<HomeSection, ReactNode> = {
    hero: page ? (
      <div key="hero" data-section="hero" className={home ? 'hero site-hero' : 'hero site-banner'}>
        <p className="eyebrow">{site.value.name}</p>
        <h1>{page.title}</h1>
        {actions}
      </div>
    ) : (
      <div key="hero" data-section="hero" className="hero site-hero">
        <p className="eyebrow">Welcome</p>
        <h1>{site.value.name}</h1>
        <p>{defaultIntro(site.value)}</p>
        {actions}
      </div>
    ),
    // HTML generated by the CMS from its rich text (never typed as HTML by editors).
    content: page ? (
      <div
        key="content"
        data-section="content"
        className="card prose"
        dangerouslySetInnerHTML={{ __html: page.bodyHtml ?? '' }}
      />
    ) : null,
    highlights: home ? <Highlights key="highlights" site={site.value} portalUrl={config.APP_URL} /> : null,
    ask: home && canAsk ? <Ask key="ask" name={site.value.name} /> : null,
  };
  const order = home ? site.value.homeSections : (['hero', 'content'] as const);
  return (
    <>
      <SiteHeader site={site.value} links={links} portalUrl={config.APP_URL} />
      <main lang={site.value.locale} className="site-main">
        <DevelopmentBanner />
        <article data-testid={page ? 'cms-page' : 'default-page'} className="plain site-sections">
          {order.map((section) => blocks[section])}
        </article>
      </main>
      <SiteFooter site={site.value} portalUrl={config.APP_URL}>
        {canAsk ? (
          <p>
            <a href="/inquiry" data-testid="inquiry-link">
              Ask about a place
            </a>
          </p>
        ) : null}
      </SiteFooter>
    </>
  );
}

const KINDS: Record<string, string> = {
  school: 'School',
  kindergarten: 'Kindergarten',
  sports_academy: 'Sports academy',
  training_centre: 'Training centre',
  college: 'College',
};

/** The invitation every school's start page carries, wherever the school puts it. */
function Ask({ name }: { name: string }) {
  return (
    <section data-section="ask" aria-labelledby="site-ask" className="site-ask">
      <div>
        <h2 id="site-ask">Thinking about {name}?</h2>
        <p>Tell us about your child and the school will reply with the next steps.</p>
      </div>
      <a href="/inquiry" className="button">
        Ask about a place
      </a>
    </section>
  );
}

/** What a family can do from the start page: the platform's own services, never invented claims. */
function Highlights({ site, portalUrl }: { site: SiteInfo; portalUrl: string }) {
  return (
    <section data-section="highlights" aria-labelledby="site-highlights" className="plain site-highlights">
      <h2 id="site-highlights">For families</h2>
      <ul className="tiles">
        {site.schools.length > 0 ? (
          <li>
            <a href="/inquiry" className="tile">
              <span className="tile-icon sky">
                <Icon name="inquiries" />
              </span>
              <span>
                <span className="tile-title">Ask about a place</span>
                <span className="tile-text">Tell us about your child; the school will reply.</span>
              </span>
            </a>
          </li>
        ) : null}
        <li>
          <a href={portalUrl} className="tile">
            <span className="tile-icon">
              <Icon name="basket" />
            </span>
            <span>
              <span className="tile-title">Lunch and clubs</span>
              <span className="tile-text">Book and pay in the family portal.</span>
            </span>
          </a>
        </li>
        <li>
          <a href={portalUrl} className="tile">
            <span className="tile-icon teal">
              <Icon name="requests" />
            </span>
            <span>
              <span className="tile-title">Trips, messages and consents</span>
              <span className="tile-text">Everything for your child in one place.</span>
            </span>
          </a>
        </li>
        {site.schools.length > 1
          ? site.schools.map((school) => (
              <li key={school.name}>
                <SchoolTile school={school} portalUrl={portalUrl} />
              </li>
            ))
          : null}
      </ul>
    </section>
  );
}

/** A school on the group website: a way to its own website, when it has one. */
function SchoolTile({ school, portalUrl }: { school: SiteInfo['schools'][number]; portalUrl: string }) {
  const body = (
    <>
      <span className="tile-icon amber">
        <Icon name="apply" />
      </span>
      <span>
        <span className="tile-title">{school.name}</span>
        <span className="tile-text">{KINDS[school.kind] ?? 'Part of the group'}</span>
      </span>
    </>
  );
  return school.host ? (
    <a href={siteUrl(school.host, portalUrl)} className="tile">
      {body}
    </a>
  ) : (
    <span className="tile">{body}</span>
  );
}

function Unavailable({ name }: { name?: string }) {
  return (
    <div className="auth-page">
      <main data-testid="site-unavailable" className="auth-card" style={{ padding: 0 }}>
        <Logo size={56} />
        <h1>{name ?? 'Pythagoras'}</h1>
        <p>This website is temporarily unavailable. Please try again in a few minutes.</p>
      </main>
    </div>
  );
}
